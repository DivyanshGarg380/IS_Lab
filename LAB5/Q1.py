# Hashing

def custom_hash(message):
    hash_val = 5381
    for ch in message:
        ascii_val = ord(ch)
        hash_val = (hash_val * 33) + ascii_val
        hash_val = hash_val ^ (hash_val >> 16)
        hash_val = hash_val & 0xFFFFFFFF 
        
    return hash_val

message = input("Enter the message: ")

result = custom_hash(message)

print("Original Message:", message)
print("Hash Value:", result)
